use std::fs;
use std::path::Path;

/// Writes `apps/workbench/public/sidex-env.js` with the host platform resolved
/// from the Cargo target triple (`CARGO_CFG_TARGET_*`, set by Cargo for build
/// scripts). Unlike browser-side detection these are compile-time constants
/// that always match the SideX binary, so the webview gets the authoritative
/// `__SIDEX_ARCH__` / `__SIDEX_OS__` / `__SIDEX_TARGET_PLATFORM__` before any
/// other script runs. `packages/build/src/sidex-env` writes a Node-side copy
/// earlier in the build so the file exists when Vite packages `public/`.
fn write_sidex_env() {
    let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();

    let arch_js = match arch.as_str() {
        "aarch64" => "arm64",
        "x86_64" => "x64",
        "x86" => "x86",
        other => {
            println!(
                "cargo:warning=unknown CARGO_CFG_TARGET_ARCH={other}, falling back to x64 in sidex-env.js"
            );
            "x64"
        }
    };
    let os_js = match os.as_str() {
        "macos" => "darwin",
        "windows" => "win32",
        "linux" => "linux",
        other => {
            println!(
                "cargo:warning=unknown CARGO_CFG_TARGET_OS={other}, falling back to linux in sidex-env.js"
            );
            "linux"
        }
    };
    let target = format!("{os_js}-{arch_js}");

    // The VS Code version SideX targets, from the single `.vscode-version` file
    // at the repo root (this script runs in apps/desktop). No fallback: a wrong
    // version would be reported to every extension, so fail the build instead.
    let version_file = Path::new("../../.vscode-version");
    // The file is outside this package, and a build script that names any
    // rerun-if-changed path is only rerun for those, so name it here too.
    println!("cargo:rerun-if-changed={}", version_file.display());
    let vscode_version = fs::read_to_string(version_file)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", version_file.display()))
        .trim()
        .to_string();
    let valid = vscode_version.split('.').count() == 3
        && vscode_version
            .split('.')
            .all(|part| !part.is_empty() && part.chars().all(|c| c.is_ascii_digit()));
    assert!(
        valid,
        ".vscode-version must contain one version like 1.110.0, got {vscode_version:?}"
    );

    let content = format!(
        "// Auto-generated by packages/build/src/extension-meta/cli.ts from Node process.*.\n\
         // Do not edit - apps/desktop/build.rs regenerates it from Rust cfg on cargo build.\n\
         globalThis.__SIDEX_TAURI__ = true;\n\
         globalThis.__SIDEX_ARCH__ = {arch_js:?};\n\
         globalThis.__SIDEX_OS__ = {os_js:?};\n\
         globalThis.__SIDEX_TARGET_PLATFORM__ = {target:?};\n\
         globalThis.__SIDEX_VSCODE_VERSION__ = {vscode_version:?};\n"
    );

    let dst = Path::new("../workbench/public/sidex-env.js");
    // Only rewrite when content changed so Vite doesn't reload on every build.
    let needs_write = fs::read(dst).map_or(true, |existing| existing != content.as_bytes());
    if needs_write {
        if let Err(e) = fs::write(dst, &content) {
            println!("cargo:warning=failed to write sidex-env.js: {e}");
        }
    }
}

fn main() {
    write_sidex_env();
    let scripts_src = Path::new("../src/vs/workbench/contrib/terminal/common/scripts");
    let scripts_dst = Path::new("shell-integration");

    if scripts_src.exists() {
        fs::create_dir_all(scripts_dst).expect("Failed to create shell-integration dir");

        let shell_files = [
            "shellIntegration-rc.zsh",
            "shellIntegration-env.zsh",
            "shellIntegration-profile.zsh",
            "shellIntegration-login.zsh",
            "shellIntegration-bash.sh",
            "shellIntegration.fish",
            "shellIntegration.ps1",
        ];

        for file in &shell_files {
            let src = scripts_src.join(file);
            let dst = scripts_dst.join(file);
            if src.exists() {
                let src_bytes =
                    fs::read(&src).unwrap_or_else(|e| panic!("Failed to read {file}: {e}"));
                let needs_copy = fs::read(&dst).map_or(true, |dst_bytes| dst_bytes != src_bytes);
                if needs_copy {
                    fs::write(&dst, &src_bytes)
                        .unwrap_or_else(|e| panic!("Failed to copy {file}: {e}"));
                }
                println!("cargo:rerun-if-changed={}", src.display());
            }
        }
    }

    let ext_host_src = Path::new("extension-host");
    let ext_host_targets = [
        Path::new("target/debug/extension-host"),
        Path::new("target/release/extension-host"),
    ];
    if ext_host_src.exists() {
        for ext_host_dst in &ext_host_targets {
            fs::create_dir_all(ext_host_dst).ok();
            for file in &["server.cjs", "host.cjs"] {
                let src = ext_host_src.join(file);
                let dst = ext_host_dst.join(file);
                if src.exists() {
                    let src_bytes = fs::read(&src).unwrap_or_default();
                    let needs_copy =
                        fs::read(&dst).map_or(true, |dst_bytes| dst_bytes != src_bytes);
                    if needs_copy {
                        let _ = fs::write(&dst, &src_bytes);
                    }
                }
            }
        }
        for file in &["server.cjs", "host.cjs"] {
            let src = ext_host_src.join(file);
            if src.exists() {
                println!("cargo:rerun-if-changed={}", src.display());
            }
        }
    }

    tauri_build::build();
}
