function check(table: Record<string, { sid: string; nid: number }>, expected: string[]): void {
	const keys = Object.keys(table);
	expect(keys).toEqual(expected);
	const ids = keys.map(k => table[k]);
	for (let i = 1; i < ids.length; i++) {
		expect(ids[i].nid).toBe(ids[i - 1].nid + 1);
	}
}

describe('extHost.protocol identifier order', () => {
	it('MainContext matches VS Code 1.144 order with consecutive ids', () => {
		check(MainContext as never, MAIN_CONTEXT);
	});

	it('ExtHostContext matches VS Code 1.144 order with consecutive ids', () => {
		check(ExtHostContext as never, EXT_HOST_CONTEXT);
	});

	it('ExtHostContext ids continue directly after MainContext', () => {
		const lastMain = (MainContext as never as Record<string, { nid: number }>)[MAIN_CONTEXT[MAIN_CONTEXT.length - 1]];
		const firstExt = (ExtHostContext as never as Record<string, { nid: number }>)[EXT_HOST_CONTEXT[0]];
		expect(firstExt.nid).toBe(lastMain.nid + 1);
	});
});
