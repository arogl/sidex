/**
 * Renders `sidex-env.js`: the host platform globals the webview reads before any
 * other script runs (`index.html` loads it first). Pure so it can be unit
 * tested; the CLI that writes it lives in `../extension-meta/cli.ts`.
 *
 * `apps/desktop/build.rs` rewrites the same file from Cargo's target triple on
 * every cargo build. That value is authoritative; this Node-side copy exists so
 * the file is present when `vite build` copies `public/` into `dist/`, because
 * in `tauri build` Vite runs before cargo.
 */

const ARCH: Record<string, string> = { arm64: 'arm64', x64: 'x64', ia32: 'x86', x86: 'x86' };
const OS: Record<string, string> = { darwin: 'darwin', win32: 'win32', linux: 'linux' };

export interface SidexEnv {
	arch: string;
	os: string;
	targetPlatform: string;
}

/** Maps Node's `process.arch` / `process.platform` to the values SideX uses. */
export function resolveSidexEnv(nodeArch: string, nodePlatform: string): SidexEnv {
	const arch = ARCH[nodeArch] ?? 'x64';
	const os = OS[nodePlatform] ?? 'linux';
	return { arch, os, targetPlatform: `${os}-${arch}` };
}

export function renderSidexEnvJs(env: SidexEnv): string {
	return [
		'// Auto-generated by packages/build/src/extension-meta/cli.ts from Node process.*.',
		'// Do not edit - apps/desktop/build.rs regenerates it from Rust cfg on cargo build.',
		'globalThis.__SIDEX_TAURI__ = true;',
		`globalThis.__SIDEX_ARCH__ = ${JSON.stringify(env.arch)};`,
		`globalThis.__SIDEX_OS__ = ${JSON.stringify(env.os)};`,
		`globalThis.__SIDEX_TARGET_PLATFORM__ = ${JSON.stringify(env.targetPlatform)};`,
		''
	].join('\n');
}
